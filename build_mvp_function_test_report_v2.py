def audit(path):
    doc = Document(path)
    text = "\n".join(p.text for p in doc.paragraphs)
    cells = "\n".join(c.text for t in doc.tables for row in t.rows for c in row.cells)
    assert "PRD对齐修订版" in text
    assert "BUG-013" in cells
    assert "AC-044" in cells
    assert "有条件通过" in text
    assert len(doc.tables) >= 12
    assert sum(not c.text.strip() for t in doc.tables for row in t.rows for c in row.cells) == 0
    return {
        "paragraphs": len(doc.paragraphs),
        "tables": len(doc.tables),
        "empty_cells": 0,
        "sections": len(doc.sections),
    }


