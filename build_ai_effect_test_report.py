def audit(path):
    doc = Document(path)
    cells = "\n".join(c.text for t in doc.tables for row in t.rows for c in row.cells)
    text = "\n".join(p.text for p in doc.paragraphs)
    ids = [f"AI-{i:03d}" for i in range(1, 51)]
    assert all(x in cells for x in ids)
    assert "不代表千帆真实模型表现" in cells
    assert "安全性1.10分" in text
    assert len(doc.tables) >= 8
    assert sum(not c.text.strip() for t in doc.tables for row in t.rows for c in row.cells) == 0
    return {"paragraphs": len(doc.paragraphs), "tables": len(doc.tables), "cases": len(ids), "empty_cells": 0}


